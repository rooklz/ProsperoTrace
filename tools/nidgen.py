#!/usr/bin/env python3
"""nidgen.py — generate the agent's NID -> (module, name) lookup table.

Input: a text file, one symbol per line:

    <module> <function> <nid-as-8-hex-bytes>

    libkernel sceKernelOpen 1a2b3c4d5e6f7081
    libSceLibcInternal malloc  8f1c2a9b44d01e77

Lines starting with # and blank lines are ignored.

Output (stdout): a C source file defining

    const struct nid_entry g_nid_table[] = { ... };   // sorted by nid
    const size_t g_nid_table_count = ...;

The agent binary-searches the table. Keeping the table data-driven means
coverage grows by editing the text file, not the C code. The table ships no
Sony material: NIDs are published symbol hashes, names are public API names.
"""
import sys

def parse(path):
    entries = []
    with open(path) as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 3:
                sys.exit(f"{path}:{lineno}: want '<module> <function> <nid16hex>', got: {line!r}")
            mod, fn, nid_hex = parts
            try:
                nid = int(nid_hex, 16)
            except ValueError:
                sys.exit(f"{path}:{lineno}: bad nid {nid_hex!r}")
            if not (0 <= nid < 1 << 64):
                sys.exit(f"{path}:{lineno}: nid out of range {nid_hex!r}")
            entries.append((nid, mod, fn))
    return entries

def main():
    if len(sys.argv) != 2:
        sys.exit("usage: nidgen.py <nids.txt> > nids_table.c")
    entries = sorted(set(parse(sys.argv[1])))
    out = []
    out.append("/* generated by tools/nidgen.py - do not edit */")
    out.append('#include "nids.h"')
    out.append("")
    out.append("const struct nid_entry g_nid_table[] = {")
    for nid, mod, fn in entries:
        out.append(f'    {{ 0x{nid:016x}ull, "{mod}", "{fn}" }},')
    out.append("};")
    out.append(f"const unsigned long g_nid_table_count = {len(entries)};")
    print("\n".join(out))
    print(f"/* {len(entries)} symbols */", file=sys.stderr)

if __name__ == "__main__":
    main()
