#define TP_PH_RING   0x1111111111111111ull
#define TP_PH_TAG_E  0x2222222222222222ull
#define TP_PH_ORIG   0x3333333333333333ull
#define TP_PH_TAG_R  0x4444444444444444ull

static int patch_imm(uint8_t *p, size_t n, uint64_t placeholder, uint64_t value)
{
    size_t hits = 0;
    for (size_t i = 0; i + 8 <= n; i++) {
        if (memcmp(p + i, &placeholder, 8) == 0) {
            memcpy(p + i, &value, 8);
            hits++;
        }
    }
    return hits == 1 ? 0 : -1;
}

int trampoline_emit(uint64_t ring_va, uint64_t orig_va, uint32_t hook_index,
                    uint8_t *out, size_t cap, size_t *out_len)
{
    if (cap < sizeof(k_tramp))
        return -1;

    memcpy(out, k_tramp, sizeof(k_tramp));

    if (patch_imm(out, sizeof(k_tramp), TP_PH_RING, ring_va) != 0 ||
        patch_imm(out, sizeof(k_tramp), TP_PH_TAG_E, pt_make_tag(PT_TAG_ENTRY, hook_index)) != 0 ||
        patch_imm(out, sizeof(k_tramp), TP_PH_ORIG, orig_va) != 0 ||
        patch_imm(out, sizeof(k_tramp), TP_PH_TAG_R, pt_make_tag(PT_TAG_RET, hook_index)) != 0)
        return -1;

    if (out_len)
        *out_len = sizeof(k_tramp);
    return 0;
}